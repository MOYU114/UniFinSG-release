CREATE TABLE offers (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    slug VARCHAR(255) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    type ENUM('discount', 'deal', 'event', 'freebie') NOT NULL,
    title VARCHAR(120) NOT NULL,
    merchant TEXT NOT NULL,
    category ENUM('food', 'transport', 'housing_tuition', 'daily_shopping', 'study_digital', 'entertainment_other') NOT NULL,
    location ENUM('utown', 'kent_ridge_central', 'science', 'engineering', 'biz_computing', 'bukit_timah', 'clementi_west_coast', 'online', 'islandwide') NOT NULL,
    description MEDIUMTEXT NOT NULL,
    conditions TEXT NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    source_url TEXT NOT NULL,
    verified_at DATE NOT NULL,
    sponsored BOOLEAN NOT NULL,
    typical_saving_cents BIGINT NULL,
    status ENUM('active', 'withdrawn') NOT NULL DEFAULT 'active',
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uq_offers_slug (slug),
    INDEX idx_offers_active_dates (status, sponsored, start_date, end_date),
    INDEX idx_offers_category_location (category, location),
    CONSTRAINT chk_offers_dates CHECK (end_date >= start_date),
    CONSTRAINT chk_offers_saving CHECK (typical_saving_cents IS NULL OR typical_saving_cents >= 0),
    CONSTRAINT chk_offers_sponsored CHECK (sponsored IN (0, 1)),
    CONSTRAINT chk_offers_status CHECK (status IN ('active', 'withdrawn'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
